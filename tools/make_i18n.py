"""Generate src/lib/i18n/strings.ts from the interface texts of the original Lagar (app/i18n.py).

Usage: python3 tools/make_i18n.py /path/to/lagar
The English text is the key; Spanish and French are the values. Run again if the original texts change."""
import json, sys, pathlib

lagar = pathlib.Path(sys.argv[1]).resolve()
sys.path.insert(0, str(lagar))
from app import i18n  # noqa: E402

out = pathlib.Path(__file__).resolve().parent.parent / "src/lib/i18n/strings.ts"
strings = {k: {"es": v["es"], "fr": v["fr"]} for k, v in i18n.STRINGS.items()}
places = {k: {"en": v["en"], "es": v["es"], "fr": v["fr"]} for k, v in i18n.PLACES.items()}
out.write_text(
    "// Generated by tools/make_i18n.py from the original Lagar. Do not edit by hand.\n"
    "/** Interface texts: the English wording is the key. A \"|one\" key is a singular form (shown without the \"|one\" in English). */\n"
    f"export const STRINGS: Record<string, {{ es: string; fr: string }}> = {json.dumps(strings, ensure_ascii=False, indent=1)}\n\n"
    "/** Country and region names, from the name they are stored under. */\n"
    f"export const PLACES: Record<string, {{ en: string; es: string; fr: string }}> = {json.dumps(places, ensure_ascii=False, indent=1)}\n",
    encoding="utf-8",
)
print(len(strings), "texts,", len(places), "places")
