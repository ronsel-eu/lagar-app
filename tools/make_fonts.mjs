// Writes src/fonts.css: Archivo (OFL, from @fontsource/archivo) as woff2 only, for the weights the app uses.
// Run: node tools/make_fonts.mjs   (after npm install)
import { readFileSync, writeFileSync } from 'node:fs'

const WEIGHTS = [400, 500, 700, 800]
const SUBSETS = ['latin', 'latin-ext']
let css = '/* Generated by tools/make_fonts.mjs from @fontsource/archivo (SIL Open Font License). Do not edit by hand. */\n'
for (const subset of SUBSETS) {
  for (const w of WEIGHTS) {
    const source = readFileSync(`node_modules/@fontsource/archivo/${subset}-${w}.css`, 'utf8')
    const range = /unicode-range:\s*([^;]+);/.exec(source)?.[1]
    css += `@font-face {\n  font-family: 'Archivo';\n  font-style: normal;\n  font-display: swap;\n  font-weight: ${w};\n` +
      `  src: url(../node_modules/@fontsource/archivo/files/archivo-${subset}-${w}-normal.woff2) format('woff2');\n` +
      (range ? `  unicode-range: ${range};\n` : '') + '}\n'
  }
}
writeFileSync('src/fonts.css', css)
console.log('src/fonts.css written')
